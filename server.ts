import 'dotenv/config';
import fs from 'node:fs';
import path from 'node:path';
import express from 'express';
import { dispatchApi, type RoutableRequest } from './src/server/apiRouter';

const PORT = Number(process.env.PORT || 3000);

async function startServer() {
  const app = express();
  app.use(express.json({ limit: '1mb' }));

  // Every /api/* request goes through the shared router. Unknown API paths
  // get a JSON 404 here, so they can never fall through to the SPA fallback.
  app.all('/api/*', (req, res) => {
    void dispatchApi(req as unknown as RoutableRequest, res as unknown as Parameters<typeof dispatchApi>[1]);
  });

  if (process.env.NODE_ENV !== 'production') {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distDir = path.resolve(process.cwd(), 'dist');
    app.use(express.static(distDir));
    app.get('*', (_req, res) => {
      const indexHtml = path.join(distDir, 'index.html');
      if (fs.existsSync(indexHtml)) {
        res.sendFile(indexHtml);
      } else {
        res.status(404).send('Build artifacts not found.');
      }
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Academy server listening on http://0.0.0.0:${PORT}`);
  });
}

startServer().catch((err) => {
  console.error('Failed to start server:', err);
  process.exit(1);
});
